export type TranslationKey = keyof typeof translations['pt-BR']

// Exported for the key-parity test; app code should go through getT/useLanguage.
export { translations }

export function getT(lang: Lang) {
  const dict = translations[lang] ?? translations['pt-BR']
  return function t(key: TranslationKey, vars?: Record<string, string | number>): string {
    let str: string = (dict as Record<string, string>)[key] ?? (translations['pt-BR'] as Record<string, string>)[key] ?? key
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        str = str.replace(`{${k}}`, String(v))
      })
    }
    return str
  }
}
